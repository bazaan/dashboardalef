-- ══════════════════════════════════════════════════════════════════════════
SELECT table_name, COUNT(*) AS columnas
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name IN ('SuscriptoresBDwppECS', 'ecs_calendar_events', 'egresos_ecs', 'ecs_cita_pagos')
GROUP BY table_name
ORDER BY table_name;


