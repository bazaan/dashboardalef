INSERT INTO public.form_signatories (company_id, nombre, cargo, orden)
SELECT 'gatwick', v.nombre, 'Técnico', v.orden
FROM (VALUES
  ('Técnico 1', 1),
  ('Técnico 2', 2)
) AS v(nombre, orden)
WHERE NOT EXISTS (
  SELECT 1 FROM public.form_signatories WHERE company_id = 'gatwick'
);


-- ═══════════════════════════════════════════════════════════════════════════
-- VERIFICACIÓN
-- ═══════════════════════════════════════════════════════════════════════════
SELECT id, company_id, nombre, cargo, (firma IS NOT NULL) AS tiene_firma, activo
FROM public.form_signatories
ORDER BY company_id, orden;


