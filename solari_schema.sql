/* =========================================
   1. TABLAS PRINCIPALES (SOLARI)
   ========================================= */

-- 1.1 Procedimientos Solari
create table if not exists public.solari_procedures (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  name text not null,
  color text,
  price numeric default 0,
  discount numeric default 0
);

-- 1.2 Eventos Calendario Solari
create table if not exists public.solari_calendar_events (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  date text not null,
  time text not null,
  subject text not null,
  description text,
  procedure_id bigint, 
  client_name text,
  client_surname text,
  client_dni text,
  event_reason text
);

-- 1.3 Historial Médico Solari
create table if not exists public.solari_medical_history (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  name text not null,
  surname text not null,
  dni text not null,
  phone text,
  email text,
  date_added text,
  attachment_name text,
  attachment_data text
);

-- 1.4 Sistema de Egresos Solari
create table if not exists public.egresos_solari (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  tipo_egreso text not null,
  nombre text not null,
  precio numeric default 0,
  cantidad integer default 1,
  company_id text
);

-- 1.5 Horarios de Calendario (Working Hours)
create table if not exists public.solari_working_hours (
  id integer primary key, -- 0 a 6 referenciando los días de la semana
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  day_of_week text,
  is_working_day boolean default true,
  start_time text default '08:00',
  end_time text default '18:00',
  slot_duration_minutes integer default 30
);

