/* =========================================
   3. POLÍTICAS DE SEGURIDAD (RLS) GLOBALES
   ========================================= */

-- Activando RLS (Row Level Security) básico para evitar bloqueos
alter table public.solari_procedures enable row level security;
alter table public.solari_calendar_events enable row level security;
alter table public.solari_medical_history enable row level security;
alter table public.egresos_solari enable row level security;
alter table public.solari_working_hours enable row level security;

